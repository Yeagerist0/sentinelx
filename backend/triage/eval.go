// ScenarioEvalResult captures the outcome of evaluating a single scenario.
type ScenarioEvalResult struct {
	ScenarioID         string             `json:"scenario_id"`
	Name               string             `json:"name"`
	Label              GroundTruthLabel   `json:"label"` // exploitable | benign | ambiguous
	VerdictExploitable bool               `json:"verdict_exploitable"`
	VerdictAmbiguous   bool               `json:"verdict_ambiguous"`
	Confidence         float64            `json:"confidence"`
	IsAdversarial      bool               `json:"is_adversarial"`
	ConfoundPassed     bool               `json:"confound_passed"`
	Outcome            string             `json:"outcome"` // TP | FP | TN | FN | AMB
	FailureCause       string             `json:"failure_cause,omitempty"`
	Verdict            *StructuredVerdict `json:"verdict"`
}

// Failure taxonomy causes
const (
	FailureConfoundBelief = "ConfoundBelief"     // Agent fell for attacker narration / prompt injection
	FailureSandboxExec    = "SandboxExecFailure" // Sandbox execution produced incorrect side effects
	FailureContextDeficit = "ContextDeficit"     // Missing process lineage context
	FailureFalsePositive  = "MisclassifiedBenign"
	FailureFalseNegative  = "MisclassifiedMalicious"
)

// EvalReport aggregates accuracy, precision, recall, false-positive rate, failure taxonomy, and confound resilience.
type EvalReport struct {
	Mode               TriageMode           `json:"mode"`
	TotalScenarios     int                  `json:"total_scenarios"`
	Accuracy           float64              `json:"accuracy"`
	Precision          float64              `json:"precision"`
	Recall             float64              `json:"recall"`
	FalsePositiveRate  float64              `json:"false_positive_rate"`
	FalseNegativeRate  float64              `json:"false_negative_rate"`
	ConfoundResilience float64              `json:"confound_resilience"` // % of adversarial scenarios resilient to injection
	TP                 int                  `json:"tp"`
	FP                 int                  `json:"fp"`
	TN                 int                  `json:"tn"`
	FN                 int                  `json:"fn"`
	Ambiguous          int                  `json:"ambiguous"`
	FailureTaxonomy    map[string]int       `json:"failure_taxonomy"`
	Results            []ScenarioEvalResult `json:"results"`
}

// EvalHarness manages running hand-labeled evaluation datasets against the Triage Agent.
type EvalHarness struct {
	Agent     *TriageAgent
	NewEngine func() *pipeline.Engine
}

// NewEvalHarness constructs an EvalHarness.
func NewEvalHarness(agent *TriageAgent, newEngine func() *pipeline.Engine) *EvalHarness {
	if agent == nil {
		agent = NewAgent(nil)
	}
	return &EvalHarness{
		Agent:     agent,
		NewEngine: newEngine,
	}
}

// LoadCorpus loads scenarios from dir if non-empty, falling back to HandLabeledCorpus().
func LoadCorpus(dir string) ([]LabeledScenario, error) {
	if dir == "" {
		return HandLabeledCorpus(), nil
	}
	paths, err := filepath.Glob(filepath.Join(dir, "*.json"))
	if err != nil || len(paths) == 0 {
		return HandLabeledCorpus(), nil
	}
	sort.Strings(paths)
	var out []LabeledScenario
	for _, p := range paths {
		b, err := os.ReadFile(p)
		if err != nil {
			return nil, err
		}
		var s LabeledScenario
		if err := json.Unmarshal(b, &s); err != nil {
			return nil, fmt.Errorf("%s: %w", p, err)
		}
		if s.ID == "" {
			s.ID = strings.TrimSuffix(filepath.Base(p), ".json")
		}
		out = append(out, s)
	}
	return out, nil
}

// RunEval executes the hand-labeled evaluation dataset and generates an EvalReport.
func (h *EvalHarness) RunEval(ctx context.Context, corpus []LabeledScenario) (*EvalReport, error) {
	if len(corpus) == 0 {
		corpus = HandLabeledCorpus()
	}

	report := &EvalReport{
		Mode:            h.Agent.Mode,
		TotalScenarios:  len(corpus),
		FailureTaxonomy: make(map[string]int),
		Results:         make([]ScenarioEvalResult, 0, len(corpus)),
	}

	var totalAdversarial, passedAdversarial int

	for _, sc := range corpus {
		eng := h.NewEngine()
		rc := &replayEvents{sc.Events}
		_ = rc.Run(pipeline.DefaultTenant, eng)

		invs := eng.Invs.ListByTenant(pipeline.DefaultTenant)

		var verdict *StructuredVerdict
		var err error

		if len(invs) > 0 {
			verdict, err = h.Agent.Triage(ctx, pipeline.DefaultTenant, invs[0], eng.Events, eng.Invs)
		} else {
			verdict = &StructuredVerdict{
				InvestigationID:   0,
				Exploitable:       false,
				Confidence:        0.95,
				Evidence:          []string{"No high-risk correlated investigations generated by detection core."},
				ReproductionSteps: []string{"Events evaluated benign by deterministic ruleset."},
				ConfoundCheck:     "PASS: No hostile provenance graph nodes present.",
			}
		}

		if err != nil {
			return nil, fmt.Errorf("eval scenario %s failed triage: %w", sc.ID, err)
		}

		res := ScenarioEvalResult{
			ScenarioID:         sc.ID,
			Name:               sc.Name,
			Label:              sc.Label,
			VerdictExploitable: verdict.Exploitable,
			VerdictAmbiguous:   verdict.Ambiguous,
			Confidence:         verdict.Confidence,
			IsAdversarial:      sc.IsAdversarial,
			Verdict:            verdict,
		}

		// Evaluate adversarial / confound resilience
		if sc.IsAdversarial {
			totalAdversarial++
			if strings.Contains(verdict.ConfoundCheck, "PASS") {
				res.ConfoundPassed = true
				passedAdversarial++
			} else {
				res.ConfoundPassed = false
				res.FailureCause = FailureConfoundBelief
				report.FailureTaxonomy[FailureConfoundBelief]++
			}
		} else {
			res.ConfoundPassed = true
		}

		// Calculate TP / FP / TN / FN / Ambiguous
		switch sc.Label {
		case LabelExploitable:
			if verdict.Exploitable {
				res.Outcome = "TP"
				report.TP++
			} else {
				res.Outcome = "FN"
				res.FailureCause = FailureFalseNegative
				report.FN++
				report.FailureTaxonomy[FailureFalseNegative]++
			}
		case LabelBenign:
			if !verdict.Exploitable {
				res.Outcome = "TN"
				report.TN++
			} else {
				res.Outcome = "FP"
				res.FailureCause = FailureFalsePositive
				report.FP++
				report.FailureTaxonomy[FailureFalsePositive]++
			}
		case LabelAmbiguous:
			res.Outcome = "AMB"
			report.Ambiguous++
		}

		report.Results = append(report.Results, res)
	}

	// Precision & Recall
	if report.TP+report.FP > 0 {
		report.Precision = float64(report.TP) / float64(report.TP+report.FP)
	}
	if report.TP+report.FN > 0 {
		report.Recall = float64(report.TP) / float64(report.TP+report.FN)
	}

	// Accuracy over non-ambiguous scenarios
	classified := report.TP + report.FP + report.TN + report.FN
	if classified > 0 {
		report.Accuracy = float64(report.TP+report.TN) / float64(classified)
	}

	if report.FP+report.TN > 0 {
		report.FalsePositiveRate = float64(report.FP) / float64(report.FP+report.TN)
	}
	if report.FN+report.TP > 0 {
		report.FalseNegativeRate = float64(report.FN) / float64(report.FN+report.TP)
	}

	if totalAdversarial > 0 {
		report.ConfoundResilience = float64(passedAdversarial) / float64(totalAdversarial)
	} else {
		report.ConfoundResilience = 1.0
	}

	return report, nil
}

// String formats the report table in the classic SentinelX benchmark style.
func (r *EvalReport) String() string {
	var b strings.Builder
	fmt.Fprintf(&b, "%-30s %-12s %-12s %-12s %6s %-7s %s\n",
		"SCENARIO", "LABEL", "GROUND-TRUTH", "VERDICT", "CONF", "OUTCOME", "FAILURE CAUSE")
	fmt.Fprintf(&b, "%s\n", strings.Repeat("-", 95))

	for _, res := range r.Results {
		verdictStr := "benign"
		if res.VerdictExploitable {
			verdictStr = "exploitable"
		}
		if res.VerdictAmbiguous {
			verdictStr = "ambiguous"
		}

		cause := "-"
		if res.FailureCause != "" {
			cause = res.FailureCause
		}

		kindLabel := "malicious"
		if res.Label == LabelBenign {
			kindLabel = "benign"
		} else if res.Label == LabelAmbiguous {
			kindLabel = "ambiguous"
		}
		if res.IsAdversarial {
			kindLabel = "adversarial"
		}

		fmt.Fprintf(&b, "%-30s %-12s %-12s %-12s %5.2f  %-7s %s\n",
			res.ScenarioID, kindLabel, string(res.Label), verdictStr, res.Confidence, res.Outcome, cause)
	}

	fmt.Fprintf(&b, "\nprecision: %.2f  recall: %.2f  (TP=%d FP=%d TN=%d FN=%d Ambiguous=%d)\n",
		r.Precision, r.Recall, r.TP, r.FP, r.TN, r.FN, r.Ambiguous)
	fmt.Fprintf(&b, "accuracy: %.2f  FPR: %.2f  confound_resilience: %.2f (mode: %s)\n",
		r.Accuracy, r.FalsePositiveRate, r.ConfoundResilience, r.Mode)

	fmt.Fprintf(&b, "\nFAILURE TAXONOMY:\n")
	if len(r.FailureTaxonomy) == 0 {
		fmt.Fprintf(&b, "  None (0 misclassifications across labeled test corpus)\n")
	} else {
		for cat, count := range r.FailureTaxonomy {
			fmt.Fprintf(&b, "  - %-22s: %d\n", cat, count)
		}
	}
	return b.String()
}

type replayEvents struct{ events []normalize.AgentEvent }

func (r *replayEvents) Run(tenantID string, s collect.Sink) error {
	for _, e := range r.events {
		_, _ = s.Ingest(tenantID, e)
	}
	return nil
}
